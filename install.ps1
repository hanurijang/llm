# Run once after cloning on Windows:
# powershell -ExecutionPolicy Bypass -File .\install.ps1
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path -LiteralPath $PSScriptRoot).Path
$agent = Join-Path $repo 'agent.py'
if (-not (Test-Path -LiteralPath $agent -PathType Leaf)) {
    throw "Cannot find agent.py in repository: $repo"
}

$hasPy = $null -ne (Get-Command py -ErrorAction SilentlyContinue)
$hasPython = $null -ne (Get-Command python -ErrorAction SilentlyContinue)
if (-not ($hasPy -or $hasPython)) {
    throw "Install Python 3.10 or newer and retry."
}
$pythonArgs = if ($hasPy) { @('-3', '-c', 'import sys; assert sys.version_info >= (3, 10)') } else { @('-c', 'import sys; assert sys.version_info >= (3, 10)') }
$pythonExe = if ($hasPy) { 'py' } else { 'python' }
& $pythonExe @pythonArgs
if ($LASTEXITCODE -ne 0) {
    throw "Python 3.10 or newer is required."
}

$bin = Join-Path $env:LOCALAPPDATA 'Programs\llm\bin'
New-Item -ItemType Directory -Path $bin -Force | Out-Null
$launcher = Join-Path $bin 'llm.cmd'
if (Test-Path -LiteralPath $launcher) {
    $header = Get-Content -LiteralPath $launcher -TotalCount 1
    if ($header -ne '@rem Generated by llm install.ps1') {
        throw "Refusing to overwrite unrelated file: $launcher"
    }
}

# Keep the repository in place: the .cmd points to its absolute location.
# Escape '%' so cmd.exe does not interpret path fragments as environment variables.
$agentPath = $agent.Replace('%', '%%')
$template = @'
@rem Generated by llm install.ps1
@echo off
setlocal DisableDelayedExpansion
if defined LLM_PYTHON (
  "%LLM_PYTHON%" -u "__AGENT__" %*
  exit /b %errorlevel%
)
where py >nul 2>&1
if not errorlevel 1 (
  py -3 -u "__AGENT__" %*
) else (
  python -u "__AGENT__" %*
)
exit /b %errorlevel%
'@
$cmd = $template.Replace('__AGENT__', $agentPath)
[System.IO.File]::WriteAllText($launcher, $cmd, [System.Text.UTF8Encoding]::new($false))

# Update per-user PATH (no administrator permissions and no machine-wide changes).
$current = [Environment]::GetEnvironmentVariable('Path', 'User')
$parts = @($current -split ';' | Where-Object { $_.Trim() })
if (-not ($parts | Where-Object { $_.TrimEnd('\') -ieq $bin.TrimEnd('\') })) {
    $newPath = (@($parts) + @($bin)) -join ';'
    [Environment]::SetEnvironmentVariable('Path', $newPath, 'User')
}
if (-not (($env:Path -split ';') | Where-Object { $_.TrimEnd('\') -ieq $bin.TrimEnd('\') })) {
    $env:Path += ";$bin"
}
Write-Host "Installed: $launcher"
Write-Host "Repository: $repo"
Write-Host "Open a new PowerShell/CMD terminal, then run: llm help"
Write-Host "The command is also available in the current PowerShell process."
